#!/usr/bin/env bash
set -euo pipefail

# ============================================================
# Blockchain Masterclass — local Anvil chain setup
#
# Starts a local EVM (Anvil), deploys a Mock USDT (BEP20-style,
# 18 decimals) token, and writes a `.env.local` override that
# points the whole backend at the local node without touching
# your real `.env`.
#
# Usage:  bash local-dev/setupLocalChain.sh
# ============================================================

BACKEND_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCAL_DEV_DIR="$BACKEND_DIR/local-dev"
ENV_LOCAL_FILE="$BACKEND_DIR/.env.local"

ANVIL_RPC_URL="${ANVIL_RPC_URL:-http://127.0.0.1:8545}"
ANVIL_CHAIN_ID="${ANVIL_CHAIN_ID:-31337}"
ANVIL_PORT="${ANVIL_PORT:-8545}"

# Anvil's deterministic funded development accounts (mnemonic "test test ... junk").
# account[0] = deployer+gas wallet, account[1] = treasury, payer = account[2].
DEPLOYER_PRIVATE_KEY="0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80"
GAS_WALLET_PRIVATE_KEY="$DEPLOYER_PRIVATE_KEY"
TREASURY_WALLET_ADDRESS="0x70997970C51812dc3A010C7d01b50e0d17dc79C8"

if ! command -v anvil >/dev/null 2>&1 || ! command -v forge >/dev/null 2>&1; then
  echo "ERROR: anvil and forge (Foundry) are required. Install them from https://book.getfoundry.sh"
  exit 1
fi

if ! curl -s --max-time 2 "$ANVIL_RPC_URL" >/dev/null 2>&1; then
  echo "Starting anvil on port $ANVIL_PORT..."
  (nohup anvil --port "$ANVIL_PORT" --chain-id "$ANVIL_CHAIN_ID" > "$LOCAL_DEV_DIR/anvil.log" 2>&1 &)
  for i in $(seq 1 15); do
    if curl -s --max-time 2 "$ANVIL_RPC_URL" >/dev/null 2>&1; then
      break
    fi
    sleep 1
  done
fi

if ! curl -s --max-time 2 "$ANVIL_RPC_URL" >/dev/null 2>&1; then
  echo "ERROR: anvil did not become reachable at $ANVIL_RPC_URL (see local-dev/anvil.log)"
  exit 1
fi
echo "Anvil is running at $ANVIL_RPC_URL"

echo "Deploying Mock USDT token..."
DEPLOY_OUTPUT=$(forge create "$LOCAL_DEV_DIR/MockUsdt.sol:MockUsdt" \
  --rpc-url "$ANVIL_RPC_URL" \
  --private-key "$DEPLOYER_PRIVATE_KEY" --broadcast --json 2>&1)
USDT_CONTRACT_ADDRESS=$(printf '%s' "$DEPLOY_OUTPUT" | grep -oE '"deployedTo"\s*:\s*"0x[a-fA-F0-9]{40}"' | grep -oE '0x[a-fA-F0-9]{40}' | head -1)
if [ -z "$USDT_CONTRACT_ADDRESS" ]; then
  echo "ERROR: failed to deploy Mock USDT:"
  printf '%s\n' "$DEPLOY_OUTPUT"
  exit 1
fi
echo "Mock USDT deployed at $USDT_CONTRACT_ADDRESS"

cat > "$ENV_LOCAL_FILE" <<EOF
# Auto-generated by local-dev/setupLocalChain.sh — overrides .env for local testing only.
# Delete this file to return to the real network configuration.
BSC_RPC_URL=$ANVIL_RPC_URL
ALCHEMY_RPC_URL=$ANVIL_RPC_URL
USDT_CONTRACT_ADDRESS=$USDT_CONTRACT_ADDRESS
USDT_MIN_CONFIRMATIONS=1
GAS_WALLET_PRIVATE_KEY=$GAS_WALLET_PRIVATE_KEY
TREASURY_WALLET_ADDRESS=$TREASURY_WALLET_ADDRESS
USDT_RECEIVING_WALLET=$TREASURY_WALLET_ADDRESS

# Background jobs: poll fast so local demos complete quickly.
ENABLE_JOBS=true
ENABLE_PAYMENT_MONITOR_JOB=true
ENABLE_SWEEP_JOB=true
ENABLE_ORDER_EXPIRY_JOB=true
MONITOR_POLL_INTERVAL_MS=3000
SWEEP_POLL_INTERVAL_MS=5000
EOF

echo ""
echo "Wrote $ENV_LOCAL_FILE"
echo "Backend now points at the local Anvil node. Start it with: npm run dev"
echo "Simulate an attendee paying: node local-dev/simulateUsdtPayment.mjs <depositAddress>"